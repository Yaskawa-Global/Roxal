// The in-app escape hatch for stale-origin trouble: everything a page may
// clear about its own origin -- service workers (whose header-injection
// fetch path can outlive deploys), CacheStorage, OPFS files, localStorage,
// IndexedDB -- then a reload to refetch entry files. The HTTP cache is not
// directly clearable, but with the worker gone a reload revalidates.
// Every step is best-effort: a locked OPFS file (the running VM may hold
// handles) must not stop the rest.
async function resetSiteData() {
    try {
        const regs = await navigator.serviceWorker?.getRegistrations?.() ?? [];
        await Promise.all(regs.map(r => r.unregister().catch(() => {})));
    } catch { /* no SW support */ }
    try {
        const keys = await window.caches?.keys?.() ?? [];
        await Promise.all(keys.map(k => window.caches.delete(k).catch(() => {})));
    } catch { /* no CacheStorage */ }
    try {
        const root = await navigator.storage?.getDirectory?.();
        if (root) {
            for await (const name of root.keys())
                await root.removeEntry(name, { recursive: true }).catch(() => {});
        }
    } catch { /* no OPFS */ }
    try { localStorage.clear(); } catch { /* private mode */ }
    try {
        const dbs = await window.indexedDB?.databases?.() ?? [];
        await Promise.all(dbs.map(d => d.name && window.indexedDB.deleteDatabase(d.name)));
    } catch { /* databases() is Chromium-only */ }
    window.location.reload();
}

