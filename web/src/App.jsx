// The file named by ?file=, normalised to the bare name fs_list reports:
// `counter4`, `counter4.rox` and `/data/counter4.rox` all name the same file,
// and a link is more likely to be typed by hand than any other entry point.
// Returns null when the parameter is absent or empty.
function requestedFile() {
    const raw = (new URLSearchParams(location.search).get('file') || '').trim();
    if (!raw) return null;
    const name = raw.replace(/^.*\//, '');          // tolerate a leading path
    return name.endsWith('.rox') ? name : name + '.rox';
}
